interface GameIconProps {
  name: IconName;
  className?: string;
  /** Accessible label; omit for decorative icons next to text. */
  label?: string;
}

/** A game-icons.net SVG that takes `currentColor`, so CSS can tint it gold, ink or a seat colour. */
export function GameIcon({ name, className = '', label }: GameIconProps) {
  const Icon = ICONS[name];
  return (
    <Icon
      className={`game-icon ${className}`}
      aria-hidden={label ? undefined : true}
      aria-label={label}
      role={label ? 'img' : undefined}
      focusable="false"
    />
  );
}
